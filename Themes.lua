function _G.ApplyFexawTheme(name)
    local theme = _G.FexawThemes[name]
    if theme then
        _G.CurrentThemeConfig = theme
        _G.RainbowUI = theme.Rainbow
        if _G.UpdateMenuVisuals then
            _G.UpdateMenuVisuals()
        end
    end
end

